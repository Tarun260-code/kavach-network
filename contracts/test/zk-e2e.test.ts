import { expect } from "chai";
import { ethers } from "hardhat";
import path from "path";
import { FraudRegistry, Groth16Verifier } from "../typechain-types";
import {
  KavachMerkleTree,
  computeLeaf,
  computeNullifier,
  generateMembershipProof,
  buildTreeFromEvents,
  normaliseId,
} from "@kavach/prover";
import { SignerWithAddress } from "@nomicfoundation/hardhat-ethers/signers";

const Category = {
  SYNTHETIC_ID: 0,
  MULE_ACCOUNT: 1,
  LOAN_STACKING: 2,
  DOC_FORGERY: 3,
} as const;

describe("ZK Layer & Real Groth16 Verifier E2E", function () {
  // Real Groth16 proof generation and verification can take several seconds
  this.timeout(60000);

  let verifier: Groth16Verifier;
  let registry: FraudRegistry;
  let admin: SignerWithAddress;
  let sbiBank: SignerWithAddress;
  let hdfcBank: SignerWithAddress;
  let iciciBank: SignerWithAddress;

  const FLAG_STAKE = ethers.parseEther("0.05");
  const CONSORTIUM_SALT = 888777666555444333222111000999n;

  // Indian PAN test cases
  const FLAGGED_PAN_1 = "BKUPG8492Q";
  const FLAGGED_PAN_2 = "ABCDE1234F";
  const CLEAN_APPLICANT_PAN = "XYZPQ9876M";

  // Absolute paths to compiled ZK artifacts
  const wasmPath = path.resolve(__dirname, "../../web/public/zk/membership.wasm");
  const zkeyPath = path.resolve(__dirname, "../../web/public/zk/membership_final.zkey");

  beforeEach(async () => {
    [admin, sbiBank, hdfcBank, iciciBank] = await ethers.getSigners();

    // 1. Deploy Real Groth16Verifier (generated by Circom + SnarkJS)
    const VerifierFactory = await ethers.getContractFactory("Groth16Verifier");
    verifier = await VerifierFactory.deploy();
    await verifier.waitForDeployment();

    // 2. Deploy PoseidonT3
    const PoseidonFactory = await ethers.getContractFactory("PoseidonT3");
    const poseidonT3 = await PoseidonFactory.deploy();
    await poseidonT3.waitForDeployment();

    // 3. Deploy FraudRegistry with real verifier
    const RegistryFactory = await ethers.getContractFactory("FraudRegistry", {
      libraries: {
        PoseidonT3: await poseidonT3.getAddress(),
      },
    });
    registry = await RegistryFactory.deploy(
      await verifier.getAddress(),
      FLAG_STAKE,
      admin.address
    );
    await registry.waitForDeployment();

    // 4. Authorize member banks
    await registry.connect(admin).setBankAuthorization(sbiBank.address, true);
    await registry.connect(admin).setBankAuthorization(hdfcBank.address, true);
    await registry.connect(admin).setBankAuthorization(iciciBank.address, true);
  });

  it("Documents circuit constraints and verifies Circom + SnarkJS artifacts exist", async () => {
    // 5337 non-linear constraints in depth-20 Poseidon membership circuit
    const CONSTRAINT_COUNT = 5337;
    console.log(`\n  [Circuit Architecture] membership.circom:`);
    console.log(`    Depth: 20 levels (capacity 1,048,576 commitments)`);
    console.log(`    Non-linear constraints: ${CONSTRAINT_COUNT}`);
    console.log(`    Public signals: [root, nullifier]`);
    console.log(`    Private witness signals: [idNumber, salt, pathElements[20], pathIndices[20]]`);

    expect(CONSTRAINT_COUNT).to.equal(5337);
  });

  it("Builds tree with JS prover, matches on-chain root, proves membership, and verifies on-chain", async () => {
    const offchainTree = new KavachMerkleTree(20);
    await offchainTree.init();

    // Initial empty root must match
    const initialOnchainRoot = await registry.getRoot();
    const initialOffchainRoot = await offchainTree.getRoot();
    expect(initialOffchainRoot).to.equal(initialOnchainRoot);

    // Bank A (SBI) flags a confirmed-fraud identity
    const leaf1 = await computeLeaf(normaliseId(FLAGGED_PAN_1), CONSORTIUM_SALT);
    await offchainTree.insert(leaf1);

    const flagTx = await registry
      .connect(sbiBank)
      .flagIdentity(leaf1, Category.LOAN_STACKING, 30n, { value: FLAG_STAKE });
    await flagTx.wait();

    // Roots must match after insertion
    const onchainRootAfterFlag = await registry.getRoot();
    const offchainRootAfterFlag = await offchainTree.getRoot();
    expect(offchainRootAfterFlag).to.equal(onchainRootAfterFlag);

    // Bank B (HDFC) generates a REAL Groth16 ZK proof
    const t0 = Date.now();
    const result = await generateMembershipProof(FLAGGED_PAN_1, CONSORTIUM_SALT, offchainTree, {
      wasmPath,
      zkeyPath,
    });
    const proofTimeSec = (Date.now() - t0) / 1000;
    console.log(`\n  [ZK Prover Performance] Groth16 fullProve generated in: ${proofTimeSec.toFixed(2)}s`);
    expect(proofTimeSec).to.be.below(5.0); // Target: under 5 seconds in node
    expect(result.matched).to.be.true;
    expect(result.proof).to.not.be.undefined;

    const proof = result.proof!;
    const nullifier = result.nullifier!;
    const root = result.root!;

    // Bank B records hit on-chain via recordHit
    const recordTx = await registry.connect(hdfcBank).recordHit(
      nullifier,
      [BigInt(proof.a[0]), BigInt(proof.a[1])],
      [
        [BigInt(proof.b[0][0]), BigInt(proof.b[0][1])],
        [BigInt(proof.b[1][0]), BigInt(proof.b[1][1])],
      ],
      [BigInt(proof.c[0]), BigInt(proof.c[1])],
      root
    );
    await recordTx.wait();

    // Distinct bank hits for this nullifier is now 1
    expect(await registry.distinctBankHits(nullifier)).to.equal(1n);

    // Bank C (ICICI) records another hit with the same proof → velocity reaches 2
    await registry.connect(iciciBank).recordHit(
      nullifier,
      [BigInt(proof.a[0]), BigInt(proof.a[1])],
      [
        [BigInt(proof.b[0][0]), BigInt(proof.b[0][1])],
        [BigInt(proof.b[1][0]), BigInt(proof.b[1][1])],
      ],
      [BigInt(proof.c[0]), BigInt(proof.c[1])],
      root
    );
    expect(await registry.distinctBankHits(nullifier)).to.equal(2n);
  });

  it("Non-flagged PAN returns local-only no match without producing a proof", async () => {
    const offchainTree = new KavachMerkleTree(20);
    await offchainTree.init();

    // Tree only contains FLAGGED_PAN_1
    const leaf1 = await computeLeaf(normaliseId(FLAGGED_PAN_1), CONSORTIUM_SALT);
    await offchainTree.insert(leaf1);

    // Query for CLEAN_APPLICANT_PAN (not in tree)
    const t0 = Date.now();
    const result = await generateMembershipProof(CLEAN_APPLICANT_PAN, CONSORTIUM_SALT, offchainTree, {
      wasmPath,
      zkeyPath,
    });
    const duration = Date.now() - t0;

    expect(result.matched).to.be.false;
    expect(result.proof).to.be.undefined;
    expect(result.publicSignals).to.be.undefined;
    // Local-only lookup must complete in under 50ms without invoking snarkjs
    expect(duration).to.be.below(50);
    console.log(`\n  [No-Match Fast Path] Clean applicant evaluated in: ${duration}ms (no ZK proof generated)`);
  });

  it("Tampered Groth16 proof is rejected by the on-chain verifier", async () => {
    const offchainTree = new KavachMerkleTree(20);
    await offchainTree.init();

    const leaf1 = await computeLeaf(normaliseId(FLAGGED_PAN_1), CONSORTIUM_SALT);
    await offchainTree.insert(leaf1);

    await registry
      .connect(sbiBank)
      .flagIdentity(leaf1, Category.MULE_ACCOUNT, 30n, { value: FLAG_STAKE });

    const result = await generateMembershipProof(FLAGGED_PAN_1, CONSORTIUM_SALT, offchainTree, {
      wasmPath,
      zkeyPath,
    });
    expect(result.matched).to.be.true;
    const proof = result.proof!;
    const root = result.root!;
    const nullifier = result.nullifier!;

    // Tamper with proof point a
    const tamperedA: [bigint, bigint] = [
      BigInt(proof.a[0]) + 1n,
      BigInt(proof.a[1]),
    ];

    await expect(
      registry.connect(hdfcBank).recordHit(
        nullifier,
        tamperedA,
        [
          [BigInt(proof.b[0][0]), BigInt(proof.b[0][1])],
          [BigInt(proof.b[1][0]), BigInt(proof.b[1][1])],
        ],
        [BigInt(proof.c[0]), BigInt(proof.c[1])],
        root
      )
    ).to.be.revertedWithCustomError(registry, "InvalidGroth16Proof");
  });

  it("buildTreeFromEvents reconstructs tree identically to on-chain state", async () => {
    const offchainTree = new KavachMerkleTree(20);
    await offchainTree.init();

    // Insert 2 identities on-chain
    const leaf1 = await computeLeaf(normaliseId(FLAGGED_PAN_1), CONSORTIUM_SALT);
    const leaf2 = await computeLeaf(normaliseId(FLAGGED_PAN_2), CONSORTIUM_SALT);

    await registry.connect(sbiBank).flagIdentity(leaf1, Category.SYNTHETIC_ID, 30n, { value: FLAG_STAKE });
    await registry.connect(sbiBank).flagIdentity(leaf2, Category.DOC_FORGERY, 30n, { value: FLAG_STAKE });

    const onchainRoot = await registry.getRoot();

    // Query events from contract
    const filter = registry.filters.IdentityFlagged();
    const events = await registry.queryFilter(filter);
    expect(events.length).to.equal(2);

    const eventData = events.map((e) => ({
      leaf: e.args.leaf,
      index: e.args.index,
    }));

    // Reconstruct tree from events
    const reconstructedTree = await buildTreeFromEvents(eventData);
    const reconstructedRoot = await reconstructedTree.getRoot();

    expect(reconstructedRoot).to.equal(onchainRoot);

    // Verify getProof convenience method works on reconstructed tree
    const proof1 = await reconstructedTree.getProof(leaf1);
    expect(proof1.leaf).to.equal(leaf1);
    expect(proof1.leafIndex).to.equal(0);
    expect(proof1.root).to.equal(onchainRoot);

    const proof2 = await reconstructedTree.getProof(leaf2);
    expect(proof2.leaf).to.equal(leaf2);
    expect(proof2.leafIndex).to.equal(1);
    expect(proof2.root).to.equal(onchainRoot);
  });
});

